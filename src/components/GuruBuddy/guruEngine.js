/**
 * Calculates current Path to Legend statistics, rank, and distance to next rank.
 */
export function getPathToLegendStats(completedNodes = []) {
  const safeCompleted = Array.isArray(completedNodes) ? completedNodes : [];
  const count = safeCompleted.length;
  const total = campaignData.rounds.reduce((acc, r) => acc + (r.nodes?.length || 0), 0) || 72;
  const percent = Math.min(100, Math.round((count / (total || 1)) * 100));

  const RANKS = [
    { title: "Apprentice", minPct: 0 },
    { title: "Novice", minPct: 10 },
    { title: "Trainee", minPct: 20 },
    { title: "Adept", minPct: 30 },
    { title: "Engineer", minPct: 40 },
    { title: "Synthesist", minPct: 50 },
    { title: "Producer", minPct: 60 },
    { title: "Virtuoso", minPct: 70 },
    { title: "Master", minPct: 80 },
    { title: "Guru", minPct: 90 },
    { title: "Legend", minPct: 100 }
  ];

  let currentRankIdx = 0;
  for (let i = RANKS.length - 1; i >= 0; i--) {
    if (percent >= RANKS[i].minPct) {
      currentRankIdx = i;
      break;
    }
  }

  const currentRank = RANKS[currentRankIdx].title;
  const nextRank = currentRankIdx < RANKS.length - 1 ? RANKS[currentRankIdx + 1].title : null;
  const nextRankMinPct = currentRankIdx < RANKS.length - 1 ? RANKS[currentRankIdx + 1].minPct : 100;
  const nextRankMinNodes = Math.ceil((nextRankMinPct / 100) * total);
  const nodesToNextRank = Math.max(0, nextRankMinNodes - count);

  return {
    count,
    total,
    percent,
    currentRank,
    nextRank,
    nodesToNextRank
  };
}

/**
 * Finds the next unlocked, uncompleted node on the Path to Legend campaign map.
 */
export function getNextCampaignNode(campaignCompleted = [], courseData = {}) {
  const completedNodes = Array.isArray(campaignCompleted) ? campaignCompleted : [];

  for (let rIdx = 0; rIdx < campaignData.rounds.length; rIdx++) {
    const round = campaignData.rounds[rIdx];
    for (let nIdx = 0; nIdx < round.nodes.length; nIdx++) {
      const node = round.nodes[nIdx];
      if (completedNodes.includes(node.id)) continue;

      let isUnlocked = false;
      if (rIdx === 0 && nIdx === 0) {
        isUnlocked = true;
      } else if (nIdx === 0 && !round.title.includes('Exam')) {
        isUnlocked = true;
      } else if (nIdx > 0) {
        const prevNode = round.nodes[nIdx - 1];
        isUnlocked = completedNodes.includes(prevNode.id);
      } else if (nIdx === 0 && round.title.includes('Exam') && rIdx > 0) {
        const prevRound = campaignData.rounds[rIdx - 1];
        if (prevRound) {
          const lastNode = prevRound.nodes[prevRound.nodes.length - 1];
          isUnlocked = completedNodes.includes(lastNode.id);
        }
      }

      if (isUnlocked) {
        let targetItem = null;
        if (node.type === 'course') {
          for (const section of (courseData.sections || [])) {
            for (const item of (section.items || [])) {
              if (item.id === node.quizId || item.title === node.title) {
                targetItem = { ...item, campaignNodeId: node.id };
                break;
              }
            }
            if (targetItem) break;
          }
        } else if (node.type === 'exam') {
          let examId = 'c3_funk';
          let examType = 'component3_exam';
          if (node.quizId === 'exam_1') examId = 'c3_funk';
          else if (node.quizId === 'exam_2') { examId = 'c4_edm'; examType = 'component4_exam'; }
          else if (node.quizId === 'exam_3') examId = 'c3_heavyrock';
          else if (node.quizId === 'exam_4') { examId = 'c4_spop'; examType = 'component4_exam'; }
          else if (node.quizId === 'exam_5') examId = 'c3_synthpop';
          targetItem = { type: examType, id: examId, title: node.title, campaignNodeId: node.id };
        } else if (node.type === 'roulette') {
          targetItem = {
            type: 'lp_quiz',
            id: 'russian_roulette_mega_quiz',
            title: 'Russian Roulette: Mega Quiz',
            campaignNodeId: node.id
          };
        }

        return {
          node,
          roundIndex: rIdx + 1,
          roundTitle: round.title,
          targetItem: targetItem || { id: node.quizId || node.id, type: 'lp_quiz', title: node.title, campaignNodeId: node.id }
        };
      }
    }
  }
  return null;
}

/**
 * Calculates current UK Academic Phase and countdown to May exams.
 */
export function getCurrentAcademicPhase(referenceDate = new Date()) {
  const month = referenceDate.getMonth(); // 0 = Jan ... 4 = May ... 11 = Dec

  let id = 'HT1';
  let name = 'Autumn 1 (Sep–Oct)';
  let isExamSeason = false;
  let termTheme = 'Coursework Launch & Exam Foundations';

  if (month === 8 || month === 9) {
    id = 'HT1';
    name = 'Autumn 1 (Sep–Oct)';
    termTheme = 'Component 1 & 2 Setup + Core Foundations';
  } else if (month === 10 || month === 11) {
    id = 'HT2';
    name = 'Autumn 2 (Nov–Dec)';
    termTheme = 'Coursework Production & Mics/Synthesis Mastery';
  } else if (month === 0 || month === 1) {
    id = 'HT3';
    name = 'Spring 1 (Jan–Feb)';
    termTheme = 'Mixing, Dynamics & Knowledge Hole Sweep';
  } else if (month === 2 || month === 3) {
    id = 'HT4';
    name = 'Spring 2 (Mar–Apr)';
    termTheme = 'Coursework Finalization & Pre-May Revision Sprint';
    if (month === 3) isExamSeason = true;
  } else if (month === 4) {
    id = 'HT5';
    name = 'Summer 1: EXAM SPRINT (May)';
    termTheme = 'PEAK EXAM SPRINT — Plugging All Knowledge Gaps';
    isExamSeason = true;
  } else {
    id = 'HT6';
    name = 'Summer 2 (Jun–Aug)';
    termTheme = 'Head Start & Exam Review';
  }

  const currentYear = referenceDate.getFullYear();
  let targetMayYear = currentYear;
  if (month > 4) {
    targetMayYear = currentYear + 1;
  }
  const mayFirst = new Date(targetMayYear, 4, 1);
  const diffMs = mayFirst.getTime() - referenceDate.getTime();
  const daysUntilMay = Math.max(0, Math.ceil(diffMs / (1000 * 60 * 60 * 24)));

  return {
    id,
    name,
    isExamSeason,
    termTheme,
    daysUntilMay,
    month
  };
}

/**
 * Generates context-aware recommendations focused strictly on:
 * 1. Path to Legend next active node
 * 2. Holes in knowledge for the exam (unattempted topics, low scores < 70%, Q5/Q6 essay workshop)
 * 3. Component 2 stimulus & arrangement milestones
 * 4. Component 1 track sheet milestones
 */
